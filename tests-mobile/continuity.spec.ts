import { test, expect } from "@playwright/test"

test("phone discovers a desktop task, answers its request and sends to the same conversation", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.route("**/live.js?*", route => route.abort())
  await page.goto("/tests-mobile/fixture.html?continuity=1&empty=1")
  await expect(page.locator(".mobile-thread-row")).toHaveCount(0)
  await expect(page.getByRole("button", { name: /Task started on desktop/ })).toHaveCount(0)
  await page.getByRole("button", { name: "Sync conversations · Fixture server · fixture@example.invalid", exact: true }).click()
  await expect(page.getByRole("button", { name: /Task started on desktop/ })).toBeVisible()
  await expect(page.getByText("Conversations synced.", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: /Task started on desktop/ }).click()
  await expect(page.locator(".agent-workspace--mobile")).toBeVisible()
  await expect(page.locator(".agent-user-text")).toContainText("Verify the shared remote project.")
  const request = page.locator(".agent-request-card.is-active")
  await expect(request).toContainText("Run the shared test suite")
  await request.getByRole("button", { name: "Allow once", exact: true }).click()
  await expect(page.locator(".agent-request-card.is-resolved")).toContainText("Approval sent")
  await expect(page.locator(".agent-prose")).toContainText("Shared tests finished.")
  await page.getByRole("button", { name: "Write a message", exact: true }).click()
  await page.getByLabel("Message agent", { exact: true }).fill("Continue the task from my phone")
  await page.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(page.locator(".agent-user-text").last()).toHaveText("Continue the task from my phone")
  await expect(page.locator(".agent-prose").last()).toContainText("Continued the desktop task from this phone.")
  const calls = await page.evaluate(() => (window as any).mobileContinuityFixture.syncCalls as string[])
  expect(calls).toContain("attach:desktop-shared-execution")
  expect(calls).toContain("answer:desktop-shared-execution:shared-approval")
  expect(calls).toContain("send:desktop-shared-execution")
})

