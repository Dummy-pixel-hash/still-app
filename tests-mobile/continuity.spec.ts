test("77 legacy records stay behind optional details while synced desktop titles remain usable", async ({ page }, testInfo) => {
  await page.goto("/tests-mobile/fixture.html?continuity=1&empty=1&legacyWarnings=1&manyLegacy=1&restoreTitle=1")
  await page.getByRole("button", { name: "Sync conversations · Fixture server · fixture@example.invalid", exact: true }).click()
  const status = page.getByRole("region", { name: "Conversation sync for Fixture server" })
  await expect(status.getByRole("status").last()).toHaveText("Conversations synced.")
  await expect(status.getByRole("alert")).toHaveCount(0)
  const details = status.locator("details").filter({ hasText: "77 older records were not imported" })
  await expect(details).not.toHaveAttribute("open", "")
  await expect(details.getByText("old-worker-1", { exact: true })).toBeHidden()
  await expect(status).not.toContainText("need review")
  await expect(status.locator(".agent-storage-notice")).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath("legacy-notes-collapsed.png") })
  await details.locator("summary").focus()
  await page.keyboard.press("Enter")
  await expect(details).toHaveAttribute("open", "")
  await expect(details.getByText("old-worker-1", { exact: true })).toBeVisible()
  const recordList = details.getByRole("region", { name: "Older record details" })
  expect(await recordList.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await recordList.focus()
  await expect(recordList).toBeFocused()
  await details.locator("summary").click()
  const thread = page.getByRole("button", { name: /Restore the original desktop title/ })
  await expect(thread).toBeVisible()
  await expect(page.getByRole("button", { name: /New OpenCode conversation/ })).toHaveCount(0)
  await thread.click()
  await expect(page.locator(".agent-workspace--mobile")).toBeVisible()
  await expect(page.locator(".agent-user-text")).toContainText("Verify the shared remote project.")
  await page.getByRole("button", { name: "Back to threads", exact: true }).click()
  await expect(thread).toBeVisible()
})

test("actual record warnings remain available for review and account failures remain visible alerts", async ({ page }) => {
  await page.goto("/tests-mobile/fixture.html?continuity=1&empty=1&unsafeRecord=1")
  await page.getByRole("button", { name: "Sync conversations · Fixture server · fixture@example.invalid", exact: true }).click()
  const status = page.getByRole("region", { name: "Conversation sync for Fixture server" })
  await expect(status.getByRole("status").last()).toHaveText("Conversations synced. 1 record needs review.")
  await status.locator("summary").filter({ hasText: "1 record needs review" }).click()
  await expect(status.getByRole("region", { name: "Sync warning details" })).toContainText("unsafe record permissions")
  await page.goto("/tests-mobile/fixture.html?continuity=1&empty=1&syncFailure=1")
  await page.getByRole("button", { name: "Sync conversations · Fixture server · fixture@example.invalid", exact: true }).click()
  await expect(status.getByRole("alert")).toContainText("account identity changed")
  await expect(status.getByText("Conversations synced.", { exact: true })).toHaveCount(0)
})

test("a competing desktop prompt stays visible while the rejected phone draft survives navigation", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/tests-mobile/fixture.html?continuity=1&empty=1&rejectSend=1")
  await page.getByRole("button", { name: "Sync conversations · Fixture server · fixture@example.invalid", exact: true }).click()
  await page.getByRole("button", { name: /Task started on desktop/ }).click()
  await page.locator(".agent-request-card.is-active").getByRole("button", { name: "Allow once", exact: true }).click()
  await expect(page.locator(".agent-request-card.is-resolved")).toContainText("Approval sent")
  await page.getByRole("button", { name: "Write a message", exact: true }).click()
  const draft = page.getByLabel("Message agent", { exact: true })
  await draft.fill("My unsent phone draft")
  await page.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(page.locator(".agent-user-text").last()).toHaveText("Continue the task from desktop instead")
  await expect(draft).toHaveValue("My unsent phone draft")
  await expect(page.getByRole("button", { name: "Send message", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Stop agent", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Back to threads", exact: true }).click()
  await page.getByRole("button", { name: /Task started on desktop/ }).click()
  await expect(page.getByLabel("Message agent", { exact: true })).toHaveValue("My unsent phone draft")
  await expect(page.locator(".agent-user-text").filter({ hasText: "My unsent phone draft" })).toHaveCount(0)
})
