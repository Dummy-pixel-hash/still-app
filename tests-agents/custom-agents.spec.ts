import { test, expect } from "@playwright/test"

const url = "/tests-agents/custom-fixture.html"
async function settings(page: import("@playwright/test").Page) {
  await page.getByRole("button", { name: "Agent settings", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Agent settings" })).toBeVisible()
}
async function add(page: import("@playwright/test").Page) {
  await page.getByRole("button", { name: "Add custom agent", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Add custom agent", exact: true })
  await dialog.getByLabel("Custom agent name").fill("Orbit CLI")
  await dialog.getByLabel("Custom agent executable").fill("/opt/agents/orbit cli")
  await dialog.getByRole("button", { name: "Add argument", exact: true }).click()
  await dialog.getByLabel("Argument 1", { exact: true }).fill("--acp")
  await dialog.getByRole("button", { name: "Add argument", exact: true }).click()
  await dialog.getByLabel("Argument 2", { exact: true }).fill("literal $(no-shell) value")
  return dialog
}

test("server-scoped custom setup, explicit test, save/reload, edit and remove", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message))
  await page.goto(url); await settings(page)
  const dialog = await add(page)
  expect(await page.evaluate(() => (window as any).customFixture.tests)).toBe(0)
  await page.screenshot({ path: "/tmp/still-custom-agent-desktop.png" })
  await dialog.getByRole("button", { name: "Test connection", exact: true }).click()
  await expect(dialog.getByRole("status")).toHaveText("Ready — ACP connection verified.")
  await dialog.getByLabel("Custom agent executable").fill("/opt/agents/orbit cli updated")
  await expect(dialog.getByRole("status")).toContainText("Not tested")
  await dialog.getByRole("button", { name: "Save agent", exact: true }).click()
  await expect(page.getByText("Orbit CLI", { exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "Add custom agent", exact: true })).toBeFocused()
  await page.reload(); await settings(page)
  await expect(page.getByText("Orbit CLI", { exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as any).customFixture.tests)).toBe(0)
  await page.getByLabel("Settings server").selectOption({ label: "beta · dev@beta.example" })
  await expect(page.getByText("Orbit CLI", { exact: true })).toHaveCount(0)
  await page.getByLabel("Settings server").selectOption({ label: "alpha · dev@alpha.example" })
  await page.getByRole("button", { name: "Edit", exact: true }).click()
  const editing = page.getByRole("dialog", { name: "Edit custom agent", exact: true })
  await expect(editing.getByLabel("Argument 2", { exact: true })).toHaveValue("literal $(no-shell) value")
  await editing.getByLabel("Custom agent executable").fill("bad-cli")
  await editing.getByRole("button", { name: "Test connection", exact: true }).click()
  await expect(editing.getByRole("alert")).toContainText("did not speak ACP")
  await editing.getByLabel("Custom agent executable").fill("orbit")
  await editing.getByRole("button", { name: "Save agent", exact: true }).click()
  await page.getByRole("button", { name: "Remove", exact: true }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(page.getByText("Orbit CLI", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Remove", exact: true }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Remove agent", exact: true }).click()
  await expect(page.getByText("Orbit CLI", { exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Add custom agent", exact: true })).toBeFocused()
  expect(errors).toEqual([])
})

test("saved custom agent is selectable and launches with literal arguments", async ({ page }) => {
  await page.goto(url); await settings(page)
  await (await add(page)).getByRole("button", { name: "Save agent", exact: true }).click()
  await page.getByRole("button", { name: "New conversation", exact: true }).click()
  await page.getByRole("button", { name: "Choose project", exact: true }).click()
  await page.locator(".agent-project-choice").first().click()
  await page.getByRole("button", { name: "Coding agent: OpenCode", exact: true }).click()
  await page.getByRole("option", { name: /Orbit CLI/ }).click()
  await expect.poll(async () => page.evaluate(() => (window as any).customFixture.launches.filter((row: any) => row.id.startsWith("custom-")).length)).toBe(1)
  const launched = await page.evaluate(() => (window as any).customFixture.launches.find((row: any) => row.id.startsWith("custom-")))
  expect(launched.options.customAgent).toMatchObject({ name: "Orbit CLI", executable: "/opt/agents/orbit cli", args: ["--acp", "literal $(no-shell) value"], transport: "acp-v1", hostKey: '["alpha.example",22,"dev"]' })
})

test("custom setup is keyboard accessible and fits a narrow viewport", async ({ page }) => {
  await page.goto(url); await settings(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole("button", { name: "Add custom agent", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Add custom agent", exact: true })
  await expect(dialog.getByLabel("Custom agent name")).toBeFocused()
  await dialog.getByLabel("Custom agent name").fill("Orbit CLI")
  await dialog.getByLabel("Custom agent executable").fill("orbit --acp")
  await dialog.getByRole("button", { name: "Save agent", exact: true }).click()
  await expect(dialog.getByRole("alert")).toContainText("without shell arguments")
  const bounds = await dialog.boundingBox()
  expect(bounds!.width).toBeLessThanOrEqual(390)
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: "/tmp/still-custom-agent-mobile.png" })
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Add custom agent", exact: true })).toBeFocused()
})
