test("reading position and draft survive new output and a trip through Changes", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/tests-agents/fixture.html?demo")
  await page.locator(".agent-recent").first().click()
  await page.evaluate(() => {
    const h = (window as any).agentFixture
    h.emit(h.current, { type: "userMessage", text: "Make a long report" })
    h.emit(h.current, { type: "assistantChunk", text: Array.from({ length: 60 }, (_, i) => `Report paragraph ${i + 1}: review the existing project and keep this context readable.`).join("\n\n") })
  })
  const viewport = page.getByLabel("Conversation", { exact: true })
  await expect.poll(() => viewport.evaluate(el => el.scrollHeight - el.clientHeight)).toBeGreaterThan(500)
  await viewport.evaluate(el => { el.scrollTop = 300 })
  await expect(page.getByRole("button", { name: "Latest activity" })).toBeVisible()
  const before = await viewport.evaluate(el => el.scrollTop)
  await page.evaluate(() => {
    const h = (window as any).agentFixture
    h.emit(h.current, { type: "assistantChunk", text: "\n\nAdditional streamed output." })
    h.finish()
  })
  await expect.poll(() => viewport.evaluate(el => el.scrollTop)).toBeCloseTo(before, 0)
  const input = page.getByLabel("Message agent")
  await input.fill("Keep this draft while reviewing")
  const trigger = page.getByRole("button", { name: "Review changes", exact: true })
  await trigger.click()
  await page.getByRole("button", { name: "Back to chat" }).click()
  await expect(trigger).toBeFocused()
  await expect(input).toHaveValue("Keep this draft while reviewing")
  await expect.poll(() => viewport.evaluate(el => el.scrollTop)).toBeCloseTo(before, 0)
  await page.getByRole("button", { name: "Latest activity" }).click()
  await expect(page.getByRole("button", { name: "Latest activity" })).toHaveCount(0)
  await expect(viewport).toBeFocused()
})

