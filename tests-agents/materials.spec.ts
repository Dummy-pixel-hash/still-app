import { test, expect } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
})

test("sidebar actions and conversation review use the same warm glass materials", async ({ page }) => {
  await page.setViewportSize({ width: 1456, height: 896 })
  await page.goto("/tests-agents/fixture.html?demo")
  const sidebar = page.locator(".agent-sidebar")
  const create = sidebar.getByRole("button", { name: "New conversation", exact: true })
  await expect(create).toHaveCSS("border-top-width", "1px")
  await expect(create).toHaveCSS("border-radius", "10px")
  await expect(create.locator("svg path")).toHaveAttribute("d", /^M12\.5 4\.5/)
  await sidebar.locator(".agent-thread-open").first().click()
  await expect(page.locator(".agent-composer-hint")).toHaveCount(0)
  await expect(page.locator(".agent-message-user").first()).toHaveCSS("background-color", "rgba(24, 22, 23, 0.5)")
  await expect(page.locator(".agent-conversation")).toHaveCSS("backdrop-filter", "blur(12px)")
  const summary = page.locator(".agent-change-summary")
  await expect(summary).toHaveCSS("background-color", "rgba(24, 22, 23, 0.5)")
  await expect(summary).toHaveCSS("border-radius", "12px")
  await expect(summary.locator("svg path").first()).toHaveAttribute("d", /^M8 3\.5/)
  await page.getByRole("button", { name: "Review changes", exact: true }).click()
  const review = page.locator(".agent-review")
  await expect(review).toHaveCSS("backdrop-filter", "blur(24px) saturate(1.1)")
  await expect(review).toHaveCSS("background-color", "rgba(10, 9, 10, 0.88)")
  await expect(review.locator(".agent-review-files > button.is-selected")).toHaveCSS("background-color", /rgba\(163, 66, 82,/)
  await expect(review.locator(".diff-add").first()).toHaveCSS("color", "rgb(178, 221, 197)")
  await expect(review.locator(".diff-remove").first()).toHaveCSS("color", "rgb(237, 187, 201)")
  await expect(page.locator(".agent-composer-hint")).toHaveCount(0)
  await page.getByRole("button", { name: "Close changes", exact: true }).click()
  await expect(review).toHaveCount(0)
  await expect(page.getByLabel("Message agent")).toBeVisible()
})

test("model menus and request forms keep their behavior in the shared material system", async ({ page }) => {
  await page.goto("/tests-agents/fixture.html?demo&scenario=models")
  const models = page.getByRole("dialog", { name: "Model and reasoning", exact: true })
  await expect(models).toHaveCSS("background-color", "rgba(15, 14, 15, 0.94)")
  await expect(models).toHaveCSS("backdrop-filter", "blur(24px) saturate(1.1)")
  await expect(page.getByRole("option", { name: "Claude Sonnet 4", exact: true })).toHaveCSS("background-color", /rgba\(163, 66, 82,/)
  await page.getByRole("button", { name: "Done", exact: true }).click()
  await expect(models).toHaveCount(0)
  await page.goto("/tests-agents/fixture.html?demo&scenario=question")
  await expect(page.locator(".agent-request-card")).toHaveCSS("background-color", "rgba(24, 22, 23, 0.5)")
  await expect(page.getByRole("radio", { name: "Extend the existing session", exact: true })).toBeVisible()
  await page.goto("/tests-agents/fixture.html?demo&scenario=approval")
  const allow = page.getByRole("button", { name: "Allow once", exact: true })
  await expect(allow).toBeVisible()
  await expect(allow).toHaveCSS("background-color", "rgb(232, 226, 228)")
  await expect(page.locator(".agent-request-permission")).toHaveCSS("border-top-color", /rgba\(211, 174, 116,/)
  await expect(page.locator(".agent-composer-hint")).toHaveCount(0)
})

test("the real application entry opens the shared Agents UI, not a fixture-only skin", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto("/")
  await page.getByRole("button", { name: "Agents", exact: true }).click()
  const workspace = page.getByRole("dialog", { name: "Agents workspace", exact: true })
  await expect(workspace).toBeVisible()
  await expect(workspace.getByRole("heading", { name: "What will you build?" })).toBeVisible()
  await expect(workspace.locator(".agent-aurora")).toHaveAttribute("data-rendered", "true")
  await expect(workspace.locator(".agent-composer")).toHaveCSS("backdrop-filter", "blur(28px) saturate(1.15)")
  await expect(workspace.locator(".agent-sidebar-new")).toHaveCSS("border-top-width", "1px")
  await expect(workspace.locator(".agent-sidebar-new svg path")).toHaveAttribute("d", /^M12\.5 4\.5/)
  await expect(workspace.locator(".agent-composer-hint")).toHaveCount(0)
  await expect(workspace.getByLabel("Message agent")).toHaveAccessibleDescription("Enter to send. Shift+Enter for a new line. Type / for commands.")
  await expect(page.locator("[data-impeccable-variants]")).toHaveCount(0)
  await expect(page.locator('script[src*="8400/live.js"]')).toHaveCount(0)
  await workspace.getByRole("button", { name: "Agent settings", exact: true }).click()
  await expect(workspace.getByRole("heading", { name: "Agent settings", exact: true })).toBeVisible()
  await workspace.getByRole("button", { name: "Close agent workspace", exact: true }).click()
  await expect(workspace).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Agents", exact: true })).toBeVisible()
})
