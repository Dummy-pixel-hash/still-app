test("streaming does not pull readers away from older messages", async ({ page }) => {
  await page.getByRole("button", { name: "Connect OpenCode" }).click()
  await page.evaluate(() => {
    const h = (window as any).agentFixture
    h.emit(h.current, { type: "userMessage", text: "Explain the architecture" })
    h.emit(h.current, { type: "assistantChunk", text: "A long explanation.\n\n".repeat(100) })
  })
  await page.locator(".agent-conversation").evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event("scroll")) })
  await expect(page.getByRole("button", { name: "Latest activity", exact: false })).toBeVisible()
  await page.evaluate(() => { const h = (window as any).agentFixture; h.emit(h.current, { type: "assistantChunk", text: "New output" }) })
  expect(await page.locator(".agent-conversation").evaluate(el => el.scrollTop)).toBe(0)
  await page.getByRole("button", { name: "Latest activity", exact: false }).click()
  await expect(page.getByRole("button", { name: "Latest activity", exact: false })).toHaveCount(0)
})

test("cached threads stay read-only after Still restarts", async ({ page }) => {
  await page.getByRole("button", { name: "Connect OpenCode" }).click()
  await page.getByLabel("Message agent").fill("Saved conversation")
  await page.getByLabel("Message agent").press("Enter")
  await page.evaluate(() => (window as any).agentFixture.finish())
  await page.reload()
  await expect(page.getByRole("alert")).toContainText("transcript is read-only")
  await page.getByLabel("Message agent").fill("Do not send")
  await expect(page.getByRole("button", { name: "Send", exact: false })).toBeDisabled()
  await expect(page.locator(".agent-message-assistant")).toContainText("First second third.")
})
