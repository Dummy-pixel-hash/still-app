test("all advertised settings work and rejection keeps the acknowledged value", async ({ page }) => {
  await page.getByRole("button", { name: "Connect OpenCode" }).click()
  await page.getByLabel("Model", { exact: true }).selectOption("b")
  await expect(page.getByLabel("Model", { exact: true })).toHaveValue("b")
  await page.getByLabel("Mode", { exact: true }).selectOption("code")
  await page.getByLabel("Reasoning", { exact: true }).selectOption("high")
  await expect(page.getByLabel("Reasoning", { exact: true })).toHaveValue("high")
  await page.evaluate(() => { (window as any).agentFixture.rejectConfig = true })
  await page.getByLabel("Model", { exact: true }).selectOption("a")
  await expect(page.getByRole("alert")).toContainText("The agent rejected that setting.")
  await expect(page.getByLabel("Model", { exact: true })).toHaveValue("b")
})

