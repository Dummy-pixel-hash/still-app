import { test, expect, type Page } from "@playwright/test"

test.beforeEach(async ({ page }) => { await page.goto("/tests-agents/fixture.html") })
async function connect(page: Page, agent = "opencode") {
  await expect(page.getByLabel("Agent", { exact: true })).toBeVisible()
  await page.getByLabel("Agent", { exact: true }).selectOption(agent)
  await page.getByRole("button", { name: "Conversation settings", exact: true }).click()
  await page.getByRole("button", { name: `Connect ${agent === "pi" ? "Pi" : agent === "claude" ? "Claude Code" : agent === "codex" ? "Codex" : "OpenCode"}`, exact: true }).click()
  await expect(page.getByRole("button", { name: "Model: Model A" })).toBeVisible()
  await page.getByRole("button", { name: "Close conversation settings", exact: true }).click()
}
async function addFolder(page: Page, path: string) {
  await page.getByRole("button", { name: "Add project folder", exact: true }).click()
  await page.getByLabel("Remote project folder").fill(path)
  await page.getByRole("button", { name: "Open folder", exact: true }).click()
}

