test("thread drafts survive switching and uncertain submissions are not retried", async ({ page }) => {
  await page.getByRole("button", { name: "Connect OpenCode" }).click()
  await page.getByLabel("Message agent").fill("Keep this draft")
  await page.getByRole("button", { name: "New thread", exact: false }).click()
  await page.getByLabel("Agent", { exact: true }).selectOption("pi")
  await page.getByRole("button", { name: "Connect Pi", exact: true }).click()
  await page.getByLabel("Message agent").fill("Pi draft")
  await page.getByRole("button", { name: "OpenCode thread OpenCode Ready" }).click()
  await expect(page.getByLabel("Message agent")).toHaveValue("Keep this draft")
  await page.evaluate(() => { (window as any).agentFixture.rejectSend = true })
  await page.getByRole("button", { name: "Send", exact: false }).click()
  await expect(page.getByRole("alert")).toContainText("Submission is uncertain")
  await expect(page.getByLabel("Message agent")).toHaveValue("Keep this draft")
  await expect(page.getByRole("button", { name: "Send", exact: false })).toBeDisabled()
})

