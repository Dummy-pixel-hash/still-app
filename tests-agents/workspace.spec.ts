test.beforeEach(async ({ page }) => {
  // Optional live-design chrome belongs to the interactive preview, not test input.
  await page.route("**/__impeccable/**", route => route.abort())
  await page.route("**/live.js?*", route => route.abort())
  await page.goto("/tests-agents/fixture.html")
})
async function connect(page: Page, agent = "opencode", firstMessage?: string) {
  if (!await page.locator('.agent-context-line').isVisible()) await addFolder(page, "/srv/still")
  await page.locator('[data-config-id="provider"] > button').click()
  await page.getByRole("option", { name: agent === "pi" ? /^Pi\b/ : agent === "claude" ? /^Claude Code\b/ : agent === "codex" ? /^Codex\b/ : /^OpenCode\b/ }).click()
  const label = agent === "pi" ? "Pi" : agent === "claude" ? "Claude Code" : agent === "codex" ? "Codex" : "OpenCode"
  await page.getByLabel("Message agent").fill(firstMessage || `New ${label} conversation`)
  await page.getByRole("button", { name: "Send message", exact: true }).click()
  await expect(page.locator(".agent-message-assistant").last()).toContainText("First second third.")
  await page.evaluate(() => (window as any).agentFixture.finish())
  await page.getByLabel("Message agent").focus()
  await expect(page.locator(".agent-composer-provider")).toBeVisible()
  await expect(page.getByRole("button", { name: "Model: Model A" })).toBeEnabled()
}
async function addFolder(page: Page, path: string) {
  if (!await page.getByRole("button", { name: "Add project folder", exact: true }).isVisible()) await page.getByRole("button", { name: "Toggle projects" }).click()
  await page.getByRole("button", { name: "Add project folder", exact: true }).click()
  await page.getByLabel("Remote project folder").fill(path)
  await page.getByRole("button", { name: "Open folder", exact: true }).click()
}
async function refreshSession(page: Page) {
  await page.getByLabel("Message agent").press("ControlOrMeta+p")
  await page.getByLabel("Search commands").fill("refresh-session")
  await page.getByLabel("Search commands").press("Enter")
}

